import { execFileSync } from "node:child_process";
import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";

const supabaseUrl = process.env.VITE_SUPABASE_URL;
if (!supabaseUrl) throw new Error("VITE_SUPABASE_URL is required in .env.local");

const projectRef = new URL(supabaseUrl).hostname.split(".")[0];

const keys = JSON.parse(execFileSync("supabase", ["projects", "api-keys", "--project-ref", projectRef, "--reveal", "--output", "json"], { encoding: "utf8" }));
const serviceKey = keys.find((key) => key.type === "secret")?.api_key ?? keys.find((key) => key.name === "service_role")?.api_key;
if (!serviceKey) throw new Error("Authenticated Supabase server key was not available");

const accounts = [
  ["CITIZEN", "citizen.qa@terratrust.local", "QA Citizen"],
  ["GOVERNMENT", "government.qa@terratrust.local", "QA Government Officer"],
  ["SURVEYOR", "surveyor.qa@terratrust.local", "QA Surveyor"],
  ["BANK", "bank.qa@terratrust.local", "QA Bank Underwriter"],
  ["ADMIN", "admin.qa@terratrust.local", "QA Administrator"],
];

const headers = { apikey: serviceKey, Authorization: `Bearer ${serviceKey}`, "Content-Type": "application/json" };
const envLines = [];

async function request(path, options = {}) {
  const response = await fetch(`${supabaseUrl}${path}`, { ...options, headers: { ...headers, ...(options.headers ?? {}) } });
  const body = await response.text();
  let parsed;
  try { parsed = body ? JSON.parse(body) : null; } catch { parsed = body; }
  if (!response.ok) throw new Error(`${options.method ?? "GET"} ${path} ${response.status}: ${typeof parsed === "string" ? parsed : JSON.stringify(parsed)}`);
  return parsed;
}

const existingUsers = await request("/auth/v1/admin/users?per_page=100");

for (const [role, email, fullName] of accounts) {
  const password = `TTqa-${randomBytes(18).toString("base64url")}-9!`;
  const user = existingUsers?.users?.find((candidate) => candidate.email === email);
  let provisionedUser;
  if (user) {
    const response = await request(`/auth/v1/admin/users/${user.id}`, { method: "PUT", body: JSON.stringify({ password, email_confirm: true, user_metadata: { full_name: fullName, region: "Karnataka" } }) });
    provisionedUser = response?.user ?? response;
  } else {
    const response = await request("/auth/v1/admin/users", { method: "POST", body: JSON.stringify({ email, password, email_confirm: true, user_metadata: { full_name: fullName, region: "Karnataka" } }) });
    provisionedUser = response?.user ?? response;
  }
  if (!provisionedUser?.id) throw new Error(`Supabase did not return a user id for ${role}`);
  await request("/rest/v1/profiles?on_conflict=id", {
    method: "POST",
    headers: { Prefer: "resolution=merge-duplicates,return=minimal" },
    body: JSON.stringify({ id: provisionedUser.id, full_name: fullName, email, role: role.toLowerCase(), region: "Karnataka" }),
  });
  envLines.push(`VITE_TEST_${role}_EMAIL=${email}`, `VITE_TEST_${role}_PASSWORD=${password}`);
  console.log(`Provisioned ${role} (${email})`);
}

const envPath = ".env.local";
const current = existsSync(envPath) ? readFileSync(envPath, "utf8") : `VITE_SUPABASE_URL=${supabaseUrl}\n`;
const withoutQa = current.replace(/^VITE_TEST_(?:CITIZEN|GOVERNMENT|SURVEYOR|BANK|ADMIN)_(?:EMAIL|PASSWORD)=.*\n?/gm, "").replace(/\n{3,}/g, "\n\n").trimEnd();
writeFileSync(envPath, `${withoutQa}\n\n# Local QA credentials generated by scripts/provision-test-accounts.mjs\n${envLines.join("\n")}\n`);
console.log(`Wrote local QA credentials to ${envPath}; do not commit this file.`);
